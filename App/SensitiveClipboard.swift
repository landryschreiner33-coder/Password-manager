import AppKit

@MainActor final class SensitiveClipboard {
    private var task: Task<Void, Never>?
    private var changeCount: Int?
    func copy(_ value: String) {
        clear()
        let board = NSPasteboard.general
        board.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        item.setString(value, forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        board.writeObjects([item]); changeCount = board.changeCount
        task = Task { [weak self] in
            try? await Task.sleep(for: .seconds(30))
            guard !Task.isCancelled else { return }; self?.clear()
        }
    }
    func clear() {
        task?.cancel(); task = nil
        if let changeCount, NSPasteboard.general.changeCount == changeCount { NSPasteboard.general.clearContents() }
        changeCount = nil
    }
}
